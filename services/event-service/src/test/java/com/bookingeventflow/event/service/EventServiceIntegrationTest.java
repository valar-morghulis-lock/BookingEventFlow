    // =====================================================================
    // OPTIMISTIC LOCKING
    // =====================================================================

    @Test
    void concurrentUpdates_shouldFailWithOptimisticLockingException() {

        EventResponse created =
                eventService.create(
                        new CreateEventRequest(
                                "Rock Concert",
                                "Live concert",
                                Instant.parse(
                                        "2026-12-20T19:00:00Z"
                                )
                        )
                );

        UUID id = created.id();

        assertNotNull(id);

        /*
         * Load two different entity instances from two
         * different persistence contexts.
         */
        EventEntity first =
                transactionTemplate.execute(
                        status ->
                                eventRepository
                                        .findById(id)
                                        .orElseThrow()
                );

        EventEntity second =
                transactionTemplate.execute(
                        status ->
                                eventRepository
                                        .findById(id)
                                        .orElseThrow()
                );

        assertNotNull(first);
        assertNotNull(second);

        assertNotSame(
                first,
                second
        );

        assertEquals(
                id,
                first.id()
        );

        assertEquals(
                id,
                second.id()
        );

        assertEquals(
                0L,
                first.version()
        );

        assertEquals(
                0L,
                second.version()
        );

        /*
         * First transaction wins.
         */
        transactionTemplate.executeWithoutResult(
                status -> {

                    EventEntity current =
                            eventRepository
                                    .findById(id)
                                    .orElseThrow();

                    assertEquals(
                            0L,
                            current.version()
                    );

                    current.setName(
                            "Updated by transaction 1"
                    );

                    eventRepository.saveAndFlush(
                            current
                    );

                    /*
                     * Hibernate increments @Version during flush.
                     */
                    assertEquals(
                            1L,
                            current.version()
                    );
                }
        );

        /*
         * The second entity is stale.
         */
        assertEquals(
                id,
                second.id()
        );

        assertEquals(
                0L,
                second.version()
        );

        second.setName(
                "Updated by transaction 2"
        );

        assertThrows(
                OptimisticLockingFailureException.class,
                () ->
                        transactionTemplate.executeWithoutResult(
                                status -> {

                                    eventRepository.saveAndFlush(
                                            second
                                    );
                                }
                        )
        );

        /*
         * Verify that transaction 1 won.
         */
        EventEntity persisted =
                eventRepository.findById(id)
                        .orElseThrow();

        assertEquals(
                id,
                persisted.id()
        );

        assertEquals(
                "Updated by transaction 1",
                persisted.getName()
        );

        assertEquals(
                1L,
                persisted.version()
        );
    }
