    @Test
    void create_shouldPersistEvent() {

        CreateEventRequest request =
                new CreateEventRequest(
                        "Rock Concert",
                        "Live concert",
                        Instant.parse(
                                "2026-12-20T19:00:00Z"
                        )
                );

        EventResponse result =
                eventService.create(request);

        /*
         * UUID is generated by Hibernate/database.
         */
        assertNotNull(result.id());

        assertEquals(
                0L,
                result.version()
        );

        assertEquals(
                "Rock Concert",
                result.name()
        );

        assertEquals(
                "Live concert",
                result.description()
        );

        assertEquals(
                EventStatus.DRAFT,
                result.status()
        );

        EventEntity persisted =
                eventRepository.findById(result.id())
                        .orElseThrow();

        assertEquals(
                result.id(),
                persisted.id()
        );

        assertEquals(
                0L,
                persisted.version()
        );

        assertEquals(
                "Rock Concert",
                persisted.getName()
        );

        assertEquals(
                "Live concert",
                persisted.getDescription()
        );

        assertEquals(
                EventStatus.DRAFT,
                persisted.getStatus()
        );
    }

