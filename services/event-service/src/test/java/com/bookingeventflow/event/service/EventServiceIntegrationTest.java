    @Test
    void update_shouldPersistChangesAndIncrementVersion() {

        EventResponse created =
                eventService.create(
                        new CreateEventRequest(
                                "Rock Concert",
                                "Live concert",
                                Instant.parse(
                                        "2026-12-20T19:00:00Z"
                                )
                        )
                );

        assertNotNull(created.id());

        assertEquals(
                0L,
                created.version()
        );

        UpdateEventRequest updateRequest =
                new UpdateEventRequest(
                        "Rock Concert Updated",
                        "Updated concert description",
                        Instant.parse(
                                "2026-12-21T19:00:00Z"
                        )
                );

        EventResponse updated =
                eventService.update(
                        created.id(),
                        updateRequest
                );

        assertEquals(
                created.id(),
                updated.id()
        );

        assertEquals(
                1L,
                updated.version()
        );

        assertEquals(
                "Rock Concert Updated",
                updated.name()
        );

        assertEquals(
                "Updated concert description",
                updated.description()
        );

        assertEquals(
                Instant.parse(
                        "2026-12-21T19:00:00Z"
                ),
                updated.scheduledAt()
        );

        EventEntity persisted =
                eventRepository.findById(created.id())
                        .orElseThrow();

        assertEquals(
                1L,
                persisted.version()
        );

        assertEquals(
                "Rock Concert Updated",
                persisted.getName()
        );
    }

